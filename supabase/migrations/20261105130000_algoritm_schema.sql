    from private.media m where m.id = p_id and m.is_public;
$$;

create or replace function public.submit_registration(
  p_full_name text, p_phone text, p_course_id bigint, p_note text default null
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_name text := private.require_name(p_full_name);
  v_phone text := private.normalize_phone(p_phone);
  v_id bigint;
begin
  if p_course_id is null or not exists (select 1 from private.courses where id = p_course_id and is_active) then
    perform private.fail('PT400', 'Kursni tanlang');
  end if;
  perform private.rate_limit('register', v_phone, 3, interval '1 hour');
  perform private.rate_limit('register_all', 'site', 120, interval '1 hour');
  insert into private.students(full_name, phone, course_id, note, status, source)
  values (v_name, v_phone, p_course_id, private.clean(p_note, 1000), 'new', 'website')
  returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end $$;

create or replace function public.submit_payment_request(
  p_full_name text, p_phone text, p_course_id bigint, p_amount numeric,
  p_card_last4 text, p_target_month text, p_receipt_mime text, p_receipt_b64 text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_name text := private.require_name(p_full_name);
  v_phone text := private.normalize_phone(p_phone);
  v_card text := nullif(regexp_replace(coalesce(p_card_last4, ''), '\D', '', 'g'), '');
  v_month date;
  v_receipt uuid;
  v_id bigint;
begin
  if p_course_id is null or not exists (select 1 from private.courses where id = p_course_id) then
    perform private.fail('PT400', 'Kursni tanlang');
  end if;
  if p_amount is null or p_amount <= 0 or p_amount > 100000000 then
    perform private.fail('PT400', 'To‘lov summasini to‘g‘ri kiriting');
  end if;
  if v_card is not null and v_card !~ '^[0-9]{4}$' then
    perform private.fail('PT400', 'Karta raqamining faqat oxirgi 4 ta raqamini kiriting');
  end if;
  begin
    v_month := case when coalesce(p_target_month, '') ~ '^\d{4}-\d{2}'
                    then to_date(left(p_target_month, 7) || '-01', 'YYYY-MM-DD')
                    else date_trunc('month', current_date)::date end;
  exception when others then
    v_month := date_trunc('month', current_date)::date;
  end;
  if p_receipt_b64 is null or p_receipt_b64 = '' then
    perform private.fail('PT400', 'To‘lov chekini yuklang');
  end if;
  perform private.rate_limit('payment', v_phone, 5, interval '1 day');
  perform private.rate_limit('payment_all', 'site', 200, interval '1 day');
  v_receipt := private.decode_file(p_receipt_b64, p_receipt_mime, 'receipt');
  insert into private.payment_requests(full_name, phone, course_id, amount, payer_card_last4, target_month, receipt_id)
  values (v_name, v_phone, p_course_id, round(p_amount), v_card, v_month, v_receipt)
  returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end $$;

create or replace function public.submit_test(
  p_test_id bigint, p_full_name text, p_phone text, p_answers jsonb
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_name text := private.require_name(p_full_name);
  v_phone text := private.normalize_phone(p_phone);
  v_total integer;
  v_correct integer;
  v_pct numeric(5,2);
  v_clean jsonb;
begin
  if not exists (select 1 from private.online_tests where id = p_test_id and is_active) then
    perform private.fail('PT404', 'Test topilmadi yoki hozir faol emas');
  end if;
  if jsonb_typeof(p_answers) is distinct from 'object' then
    perform private.fail('PT400', 'Javoblar yuborilmadi');
  end if;
  perform private.rate_limit('test:' || p_test_id, v_phone, 10, interval '1 day');
  select count(*),
         count(*) filter (where upper(p_answers ->> q.id::text) = q.correct_option),
         coalesce(jsonb_object_agg(q.id::text, upper(p_answers ->> q.id::text))
                  filter (where upper(p_answers ->> q.id::text) in ('A','B','C','D')), '{}'::jsonb)
