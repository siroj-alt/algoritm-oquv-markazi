create or replace function public.admin_list(p_token text, p_entity text, p_filter jsonb default '{}'::jsonb)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v jsonb;
begin
  perform private.require_admin(p_token);
  case p_entity
  when 'courses' then
    select jsonb_agg(to_jsonb(c) || jsonb_build_object(
             'students_count', (select count(*) from private.students s where s.course_id = c.id))
           order by c.sort_order, c.id) into v from private.courses c;
  when 'groups' then
    select jsonb_agg(to_jsonb(g) || jsonb_build_object(
             'course_name', c.name,
             'students_count', (select count(*) from private.students s where s.group_id = g.id))
           order by g.is_active desc, g.id desc) into v
      from private.study_groups g left join private.courses c on c.id = g.course_id;
  when 'students' then
    select jsonb_agg(to_jsonb(s) || jsonb_build_object('course_name', c.name, 'group_name', g.name)
           order by s.created_at desc) into v
      from (select * from private.students order by created_at desc limit 3000) s
      left join private.courses c on c.id = s.course_id
      left join private.study_groups g on g.id = s.group_id;
  when 'payments' then
    select jsonb_agg(to_jsonb(p) || jsonb_build_object('student_name', s.full_name, 'student_phone', s.phone)
           order by p.paid_on desc, p.id desc) into v
      from (select * from private.payments order by paid_on desc, id desc limit 3000) p
      left join private.students s on s.id = p.student_id;
  when 'payment_requests' then
    select jsonb_agg(to_jsonb(r) || jsonb_build_object('course_name', c.name, 'receipt_mime', m.mime)
           order by (r.status = 'pending') desc, r.created_at desc) into v
      from (select * from private.payment_requests order by created_at desc limit 3000) r
      left join private.courses c on c.id = r.course_id
      left join private.media m on m.id = r.receipt_id;
  when 'attendance' then
    select jsonb_agg(to_jsonb(a) || jsonb_build_object('student_name', s.full_name, 'group_name', g.name)
           order by a.lesson_date desc, a.id desc) into v
      from (select * from private.attendance order by lesson_date desc, id desc limit 3000) a
      left join private.students s on s.id = a.student_id
      left join private.study_groups g on g.id = a.group_id;
  when 'tests' then
    select jsonb_agg(to_jsonb(t) || jsonb_build_object(
             'questions_count', (select count(*) from private.test_questions q where q.test_id = t.id),
             'results_count', (select count(*) from private.test_results r where r.test_id = t.id))
           order by t.id desc) into v from private.online_tests t;
  when 'questions' then
    select jsonb_agg(to_jsonb(q) order by q.sort_order, q.id) into v
      from private.test_questions q
     where q.test_id = nullif(p_filter ->> 'test_id', '')::bigint;
  when 'test_results' then
    select jsonb_agg(to_jsonb(r) - 'answers' || jsonb_build_object('test_title', t.title)
           order by r.created_at desc) into v
      from (select * from private.test_results order by created_at desc limit 3000) r
      left join private.online_tests t on t.id = r.test_id;
  when 'admins' then
    select jsonb_agg(jsonb_build_object('id', id, 'username', username, 'full_name', full_name,
             'is_active', is_active, 'last_login_at', last_login_at, 'created_at', created_at)
           order by id) into v from private.admins;
  when 'settings' then
    return private.settings_json();
  else
    perform private.fail('PT404', 'Bunday bo‘lim yo‘q');
  end case;
  return coalesce(v, '[]'::jsonb);
end $$;

create or replace function public.admin_save(p_token text, p_entity text, p_id bigint, p_data jsonb)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_table text;
  v_cols text[];
  v_list text;
  v_row jsonb;
  v_data jsonb := private.clean_payload(p_data);
  v_constraint text;
  v_column text;
begin
  perform private.require_admin(p_token);
  v_table := case p_entity
    when 'courses' then 'courses'
    when 'groups' then 'study_groups'
    when 'students' then 'students'
    when 'payments' then 'payments'
    when 'attendance' then 'attendance'
    when 'tests' then 'online_tests'
    when 'questions' then 'test_questions'
  end;
  if v_table is null then
    perform private.fail('PT404', 'Bu bo‘limni tahrirlab bo‘lmaydi');
  end if;

  if p_entity = 'students' then
    if v_data ? 'phone' then
      v_data := v_data || jsonb_build_object('phone', private.normalize_phone(v_data ->> 'phone'));
    end if;
    if p_id is null and not v_data ? 'source' then
      v_data := v_data || '{"source":"admin"}'::jsonb;
    end if;
  elsif p_entity = 'questions' and v_data ? 'correct_option' then
    v_data := v_data || jsonb_build_object('correct_option', upper(v_data ->> 'correct_option'));
  elsif p_entity = 'payments' and v_data ? 'for_month' and (v_data ->> 'for_month') ~ '^\d{4}-\d{2}$' then
    v_data := v_data || jsonb_build_object('for_month', (v_data ->> 'for_month') || '-01');
  end if;

  select array_agg(column_name::text order by ordinal_position) into v_cols
    from information_schema.columns
   where table_schema = 'private' and table_name = v_table
     and column_name::text not in ('id', 'created_at', 'updated_at', 'request_id', 'enrolled_at')
     and v_data ? column_name::text;
  if v_cols is null then
    perform private.fail('PT400', 'Saqlash uchun ma’lumot yuborilmadi');
  end if;
  select string_agg(format('%I', c), ', ') into v_list from unnest(v_cols) c;

  begin
    if p_id is null then
      execute format('insert into private.%I (%s) select %s from jsonb_populate_record(null::private.%I, $1) returning to_jsonb(%I.*)',
                     v_table, v_list, v_list, v_table, v_table)
         into v_row using v_data;
    else
      execute format('update private.%I t set (%s) = (select %s from jsonb_populate_record(null::private.%I, $1)) where t.id = $2 returning to_jsonb(t.*)',
                     v_table, v_list, v_list, v_table)
         into v_row using v_data, p_id;
      if v_row is null then
        perform private.fail('PT404', 'Yozuv topilmadi. Sahifani yangilang');
      end if;
    end if;
  exception
    when foreign_key_violation then
      perform private.fail('PT409', 'Tanlangan bog‘liq ma’lumot (kurs, guruh, o‘quvchi yoki test) topilmadi');
    when not_null_violation then
      get stacked diagnostics v_column = column_name;
      perform private.fail('PT400', 'Majburiy maydon to‘ldirilmagan: ' || coalesce(v_column, ''));
    when check_violation then
      get stacked diagnostics v_constraint = constraint_name;
      perform private.fail('PT400', 'Maydon qiymati talabga mos emas (' || coalesce(v_constraint, '') || ')');
    when unique_violation then
      perform private.fail('PT409', 'Bunday yozuv allaqachon mavjud (masalan, shu kunga davomat kiritilgan)');
    when invalid_text_representation or invalid_datetime_format or datetime_field_overflow
         or numeric_value_out_of_range or invalid_parameter_value then
      perform private.fail('PT400', 'Maydonlardan biri noto‘g‘ri formatda kiritilgan');
  end;
  return v_row;
end $$;

