-- Bo‘sh satrlarni NULL ga aylantirish va matnni tozalash
create or replace function private.clean_payload(p_data jsonb) returns jsonb
language sql immutable set search_path = '' as $$
  select coalesce(jsonb_object_agg(k,
           case
             when jsonb_typeof(v) = 'string' and btrim(v #>> '{}') = '' then 'null'::jsonb
             when jsonb_typeof(v) = 'string' then to_jsonb(btrim(v #>> '{}'))
             else v
           end), '{}'::jsonb)
    from jsonb_each(coalesce(p_data, '{}'::jsonb)) e(k, v);
$$;

