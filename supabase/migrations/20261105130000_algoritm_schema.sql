create table if not exists private.media (
  id uuid primary key default gen_random_uuid(),
  kind text not null constraint media_kind_check check (kind in ('image','receipt')),
  mime text not null constraint media_mime_check
    check (mime in ('image/jpeg','image/png','image/webp','application/pdf')),
  size_bytes integer not null constraint media_size_check
    check (size_bytes > 0 and size_bytes <= 3500000),
  data bytea not null,
  is_public boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists private.courses (
  id bigint generated by default as identity primary key,
  name text not null constraint courses_name_check check (char_length(btrim(name)) between 2 and 120),
  description text constraint courses_description_check check (char_length(description) <= 5000),
  price numeric(12,0) not null default 0 constraint courses_price_check check (price >= 0),
  duration text constraint courses_duration_check check (char_length(duration) <= 80),
  schedule text constraint courses_schedule_check check (char_length(schedule) <= 160),
  teacher_name text constraint courses_teacher_name_check check (char_length(teacher_name) <= 120),
  teacher_bio text constraint courses_teacher_bio_check check (char_length(teacher_bio) <= 2000),
  image_url text constraint courses_image_url_check
    check (image_url ~ '^(/media/[0-9a-f-]{36}|https://[^\s"<>]+)$'),
  teacher_image_url text constraint courses_teacher_image_url_check
    check (teacher_image_url ~ '^(/media/[0-9a-f-]{36}|https://[^\s"<>]+)$'),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists private.study_groups (
  id bigint generated by default as identity primary key,
  course_id bigint not null references private.courses(id) on delete restrict,
  name text not null constraint study_groups_name_check check (char_length(btrim(name)) between 1 and 100),
  teacher_name text constraint study_groups_teacher_check check (char_length(teacher_name) <= 120),
  schedule text constraint study_groups_schedule_check check (char_length(schedule) <= 160),
  start_date date,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists private.students (
  id bigint generated by default as identity primary key,
  full_name text not null constraint students_full_name_check check (char_length(btrim(full_name)) between 3 and 120),
  phone text not null constraint students_phone_check check (phone ~ '^\+[0-9]{9,15}$'),
  course_id bigint references private.courses(id) on delete set null,
  group_id bigint references private.study_groups(id) on delete set null,
  status text not null default 'new'
    constraint students_status_check check (status in ('new','contacted','enrolled','rejected')),
  note text constraint students_note_check check (char_length(note) <= 1000),
  source text not null default 'website' constraint students_source_check check (source in ('website','admin')),
  enrolled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists private.payment_requests (
  id bigint generated by default as identity primary key,
  full_name text not null constraint payment_requests_full_name_check check (char_length(btrim(full_name)) between 3 and 120),
  phone text not null constraint payment_requests_phone_check check (phone ~ '^\+[0-9]{9,15}$'),
  course_id bigint references private.courses(id) on delete set null,
  student_id bigint references private.students(id) on delete set null,
  amount numeric(12,0) not null constraint payment_requests_amount_check check (amount > 0 and amount <= 100000000),
  payer_card_last4 text constraint payment_requests_card_check check (payer_card_last4 ~ '^[0-9]{4}$'),
  target_month date,
  receipt_id uuid references private.media(id) on delete set null,
  status text not null default 'pending'
    constraint payment_requests_status_check check (status in ('pending','approved','rejected')),
  admin_note text constraint payment_requests_note_check check (char_length(admin_note) <= 500),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create table if not exists private.payments (
  id bigint generated by default as identity primary key,
  student_id bigint not null references private.students(id) on delete restrict,
  amount numeric(12,0) not null constraint payments_amount_check check (amount > 0 and amount <= 100000000),
  method text not null default 'cash'
    constraint payments_method_check check (method in ('cash','card','transfer','other')),
  paid_on date not null default current_date,
  for_month date,
  note text constraint payments_note_check check (char_length(note) <= 500),
  request_id bigint unique references private.payment_requests(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists private.attendance (
  id bigint generated by default as identity primary key,
