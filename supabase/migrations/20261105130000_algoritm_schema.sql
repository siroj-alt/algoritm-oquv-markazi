create or replace function private.fail(p_code text, p_message text) returns void
language plpgsql set search_path = '' as $$
begin
  raise exception using errcode = p_code, message = p_message;
end $$;

create or replace function private.clean(p_value text, p_max integer default 500) returns text
language sql immutable set search_path = '' as $$
  select nullif(left(btrim(regexp_replace(coalesce(p_value, ''), '[\r\t]+', ' ', 'g')), p_max), '');
$$;

create or replace function private.normalize_phone(p_phone text) returns text
language plpgsql immutable set search_path = '' as $$
declare
  d text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
begin
  if char_length(d) = 9 then
    return '+998' || d;
  elsif char_length(d) = 12 and left(d, 3) = '998' then
    return '+' || d;
  elsif char_length(d) between 10 and 15 then
    return '+' || d;
  end if;
  perform private.fail('PT400', 'Telefon raqamini to‘liq kiriting, masalan: +998 90 123 45 67');
  return null;
end $$;

create or replace function private.require_name(p_value text) returns text
language plpgsql immutable set search_path = '' as $$
declare v text := private.clean(p_value, 120);
begin
  if v is null or char_length(v) < 3 then
    perform private.fail('PT400', 'Ism va familiyani kiriting');
  end if;
  return v;
end $$;

create or replace function private.rate_limit(p_action text, p_subject text, p_max integer, p_window interval)
returns void language plpgsql set search_path = '' as $$
declare n integer;
begin
  delete from private.rate_events where created_at < now() - interval '2 days';
  select count(*) into n from private.rate_events
   where action = p_action and subject = p_subject and created_at > now() - p_window;
  if n >= p_max then
    perform private.fail('PT429', 'Juda ko‘p urinish. Birozdan keyin qayta urinib ko‘ring.');
  end if;
  insert into private.rate_events(action, subject) values (p_action, coalesce(p_subject, ''));
end $$;

create or replace function private.require_admin(p_token text) returns bigint
language plpgsql set search_path = '' as $$
declare v_admin bigint;
begin
  if p_token is null or char_length(p_token) < 32 then
    perform private.fail('PT401', 'Admin paneliga qaytadan kiring');
  end if;
  select s.admin_id into v_admin
    from private.admin_sessions s
    join private.admins a on a.id = s.admin_id and a.is_active
   where s.token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex')
     and s.expires_at > now();
  if v_admin is null then
    perform private.fail('PT401', 'Sessiya muddati tugagan. Admin paneliga qaytadan kiring');
  end if;
  return v_admin;
end $$;

create or replace function private.decode_file(p_b64 text, p_mime text, p_kind text) returns uuid
language plpgsql set search_path = '' as $$
declare
  v_bytes bytea;
  v_id uuid;
begin
  if p_mime not in ('image/jpeg','image/png','image/webp','application/pdf')
     or (p_kind = 'image' and p_mime = 'application/pdf') then
    perform private.fail('PT400', 'Fayl turi noto‘g‘ri. JPG, PNG, WEBP yoki PDF yuklang');
  end if;
  begin
    v_bytes := decode(p_b64, 'base64');
  exception when others then
    perform private.fail('PT400', 'Fayl buzilgan yoki noto‘g‘ri yuborilgan');
  end;
  if v_bytes is null or length(v_bytes) = 0 then
    perform private.fail('PT400', 'Fayl bo‘sh');
  end if;
  if length(v_bytes) > 3500000 then
    perform private.fail('PT400', 'Fayl hajmi 3 MB dan oshmasin');
  end if;
  -- Fayl imzosini tekshirish (kengaytma emas, haqiqiy tarkib)
  if not (
       (p_mime = 'image/jpeg' and substring(v_bytes from 1 for 3) = '\xffd8ff'::bytea)
    or (p_mime = 'image/png' and substring(v_bytes from 1 for 8) = '\x89504e470d0a1a0a'::bytea)
    or (p_mime = 'image/webp' and substring(v_bytes from 1 for 4) = '\x52494646'::bytea
                              and substring(v_bytes from 9 for 4) = '\x57454250'::bytea)
    or (p_mime = 'application/pdf' and substring(v_bytes from 1 for 4) = '\x25504446'::bytea)
  ) then
    perform private.fail('PT400', 'Fayl tarkibi tanlangan turga mos emas');
  end if;
  insert into private.media(kind, mime, size_bytes, data, is_public)
  values (p_kind, p_mime, length(v_bytes), v_bytes, p_kind = 'image')
  returning id into v_id;
  return v_id;
end $$;

