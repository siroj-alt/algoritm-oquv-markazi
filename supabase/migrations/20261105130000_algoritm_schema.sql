create or replace function private.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

create or replace function private.students_before_write() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.status = 'enrolled' and new.enrolled_at is null then
    new.enrolled_at := now();
  end if;
  if tg_op = 'UPDATE' then
    new.updated_at := now();
  end if;
  return new;
end $$;

drop trigger if exists courses_touch on private.courses;
create trigger courses_touch before update on private.courses
  for each row execute function private.touch_updated_at();
drop trigger if exists study_groups_touch on private.study_groups;
create trigger study_groups_touch before update on private.study_groups
  for each row execute function private.touch_updated_at();
drop trigger if exists online_tests_touch on private.online_tests;
create trigger online_tests_touch before update on private.online_tests
  for each row execute function private.touch_updated_at();
drop trigger if exists students_write on private.students;
create trigger students_write before insert or update on private.students
  for each row execute function private.students_before_write();

