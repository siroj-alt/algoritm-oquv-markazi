create or replace function public.admin_review_payment(p_token text, p_request_id bigint, p_status text, p_note text default null)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  r private.payment_requests;
  v_student bigint;
begin
  perform private.require_admin(p_token);
  if p_status not in ('approved', 'rejected') then
    perform private.fail('PT400', 'Holat noto‘g‘ri');
  end if;
  select * into r from private.payment_requests where id = p_request_id for update;
  if r.id is null then
    perform private.fail('PT404', 'To‘lov arizasi topilmadi');
  end if;
  if r.status = 'approved' then
    perform private.fail('PT409', 'Bu to‘lov allaqachon tasdiqlangan');
  end if;
  if p_status = 'approved' then
    select id into v_student from private.students
     where phone = r.phone order by (course_id = r.course_id) desc nulls last, created_at desc limit 1;
    if v_student is null then
      insert into private.students(full_name, phone, course_id, status, source)
      values (r.full_name, r.phone, r.course_id, 'enrolled', 'website') returning id into v_student;
    else
      update private.students set status = 'enrolled' where id = v_student and status in ('new', 'contacted');
    end if;
    insert into private.payments(student_id, amount, method, paid_on, for_month, note, request_id)
    values (v_student, r.amount, 'card', current_date, r.target_month,
            'Onlayn chek №' || r.id || coalesce(' (karta *' || r.payer_card_last4 || ')', ''), r.id)
    on conflict (request_id) do nothing;
  end if;
  update private.payment_requests
     set status = p_status, reviewed_at = now(), admin_note = private.clean(p_note, 500),
         student_id = coalesce(v_student, student_id)
   where id = r.id;
  return jsonb_build_object('ok', true, 'student_id', v_student);
end $$;

