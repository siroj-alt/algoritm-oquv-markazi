-- =====================================================================
-- Algoritm o‘quv markazi — Supabase (PostgreSQL) sxemasi
--
-- Xavfsizlik modeli:
--   * Barcha jadvallar `private` sxemasida. PostgREST bu sxemani
--     ko‘rsatmaydi, anon/authenticated rollarda unga ruxsat yo‘q.
--   * Sayt bazaga faqat `public` sxemadagi SECURITY DEFINER
--     funksiyalar (RPC) orqali murojaat qiladi.
--   * Admin funksiyalari har safar sessiya tokenini tekshiradi
--     (token bazada faqat SHA-256 xesh ko‘rinishida saqlanadi).
--   * Shuning uchun serverda faqat publishable (anon) kalit kifoya.
--
-- Fayl idempotent: qayta ishga tushirish xavfsiz.
-- =====================================================================

create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on schema private from anon, authenticated';
  end if;
end $$;

