create or replace function public.admin_login(p_username text, p_password text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_user text := lower(btrim(coalesce(p_username, '')));
  a private.admins;
  v_token text;
begin
  if v_user = '' or coalesce(p_password, '') = '' then
    perform private.fail('PT400', 'Login va parolni kiriting');
  end if;
  perform private.rate_limit('login', v_user, 10, interval '15 minutes');
  select * into a from private.admins where username = v_user;
  if a.id is null or not a.is_active then
    perform extensions.crypt(p_password, extensions.gen_salt('bf', 10)); -- vaqt bo‘yicha farq bo‘lmasin
    perform private.fail('PT401', 'Login yoki parol noto‘g‘ri');
  end if;
  if a.locked_until is not null and a.locked_until > now() then
    perform private.fail('PT429', 'Juda ko‘p noto‘g‘ri urinish. 15 daqiqadan keyin qayta urinib ko‘ring.');
  end if;
  if extensions.crypt(p_password, a.password_hash) <> a.password_hash then
    update private.admins
       set failed_attempts = failed_attempts + 1,
           locked_until = case when failed_attempts + 1 >= 5 then now() + interval '15 minutes' else null end
     where id = a.id;
    return jsonb_build_object('ok', false, 'error', 'Login yoki parol noto‘g‘ri');
  end if;
  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  delete from private.admin_sessions where expires_at < now();
  insert into private.admin_sessions(token_hash, admin_id, expires_at)
  values (encode(extensions.digest(v_token, 'sha256'), 'hex'), a.id, now() + interval '12 hours');
  update private.admins set failed_attempts = 0, locked_until = null, last_login_at = now() where id = a.id;
  delete from private.rate_events where action = 'login' and subject = v_user;
  return jsonb_build_object('ok', true, 'token', v_token,
    'admin', jsonb_build_object('id', a.id, 'username', a.username, 'full_name', a.full_name));
end $$;

